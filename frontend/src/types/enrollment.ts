/**
 * 受講の期間 — 受講開始日と卒業予定日。
 * ============================================================
 * 学習の記録（/study-log）のヘッダーに「卒業予定 2026年12月31日（あと85日）」を出すために持つ。
 *
 * 🔴 実BFF（FastAPI）にこの概念は存在しない。バックエンドは変更禁止のため、
 *    mocks/handlers.ts の MSW モックだけが応答する。
 *    本番（モック OFF）では取得に失敗するので、呼び出し側は null を前提に組む
 *    ＝ 値が無いときはピルごと描かない。「卒業予定 —」のような空表示にしない。
 *
 * 🔴 StudyStatsSummary に相乗りさせない。あちらは「学習の集計」で、
 *    受講契約の話とは寿命も権威も違う（学習記録を1件も持たない受講生にも卒業予定日はある）。
 *
 * 🔴 LearningPlan.goalDeadline と混ぜない。あちらはロードマップが立てた
 *    「目標期限」で、受講生が自分で動かせる。卒業予定日は動かせない。
 * ============================================================
 */
export interface Enrollment {
  /**
   * 受講開始日（YYYY-MM-DD）。取れなければ null。
   * 🔴 カレンダーの遡り下限には使わない。あちらは StudyStatsSummary.firstStudyDate が
   *    唯一の根拠（受講開始より前の記録が入っていても隠さないため）。
   */
  startDate: string | null;
  /** 卒業予定日（YYYY-MM-DD）。取れなければ null */
  graduationDate: string | null;
}
